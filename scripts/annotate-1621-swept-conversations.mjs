// TASK-1621 AC-5 — identify and annotate conversations that the pre-fix
// `session_end` swept closed.
//
// The defect: `session_end` decided EVERY conversation merely linked to the
// session and stamped each one's `decision_summary` with the session's own
// `handoff.resumePoint`. Auto-link (`conversation_open` links to the sole
// active session) made that easy to trigger on unrelated threads.
//
// Decision recorded 2026-08-09: annotate, do not reopen. Most swept threads are
// historically dead (screenshot captures, cross-team questions on long-shipped
// work) and blanket-reopening 80+ of them would flood `conversation_list` /
// `conversation_poll` with noise. The header keeps saying `decided`; what
// changes is that the lie is now labelled in the message log. Threads that are
// genuinely still open can be recovered one at a time with the
// `conversation_reopen` MCP tool.
//
// The annotation is appended with `kind='message'` and the header is NOT
// refolded, so status stays `decided` — a plain message append does not
// recompute the header (see SqliteTaskService.addConversationMessage).
//
// Usage:
//   node scripts/annotate-1621-swept-conversations.mjs            # dry run
//   node scripts/annotate-1621-swept-conversations.mjs --apply    # write
//
// Env: CHODA_DATA_DIR (default C:\dev\choda-deck\data)

import Database from 'better-sqlite3'
import * as fs from 'node:fs'
import * as path from 'node:path'

const APPLY = process.argv.includes('--apply')
const DATA_DIR = process.env.CHODA_DATA_DIR ?? path.join(process.cwd(), 'data')
const DB_PATH = path.join(DATA_DIR, 'database', 'choda-deck.db')
const REPORT_PATH = path.join(process.cwd(), 'docs', 'task-1621-swept-conversations.md')

const ANNOTATION =
  'TASK-1621 — automated correction. This conversation was closed by `session_end`, ' +
  'not by anyone deciding it. The `decisionSummary` above is the ending session\'s ' +
  '`resumePoint`, copied verbatim; it is not this thread\'s decision and may be about ' +
  'unrelated work. Treat the header as unreliable. If the question here is still open, ' +
  'reopen it with the `conversation_reopen` MCP tool.'

if (!fs.existsSync(DB_PATH)) {
  console.error(`Database not found: ${DB_PATH}`)
  process.exit(1)
}

const db = new Database(DB_PATH, { readonly: !APPLY })

// The discriminant, deliberately narrow. A conversation was SWEPT when:
//   1. its header says `decided` with a summary, but
//   2. no `decision` turn in the append-only log backs that — the header was
//      written directly, and
//   3. it is linked to a session (the sweep's blast radius), and
//   4. it is NOT an inbox-converted thread — `inbox_convert` / `inbox_archive`
//      close their own conversations with a summary that IS about them
//      (see InboxLifecycleService.closeLinkedConversations), and
//   5. it is not the session's own companion thread, whose title is
//      `Session SESSION-...` and for which the resumePoint IS the right summary.
//
// Conditions 4 and 5 matter: without them the query returns 249 rows, of which
// most were closed legitimately. Annotating those would assert a defect that
// did not happen there.
const swept = db
  .prepare(
    `SELECT c.id,
            c.title,
            c.decision_summary,
            c.decided_at,
            (SELECT l.linked_id FROM conversation_links l
              WHERE l.conversation_id = c.id AND l.linked_type = 'session') AS session_id
       FROM conversations c
      WHERE c.status = 'decided'
        AND c.decision_summary IS NOT NULL
        AND c.title NOT LIKE 'Session SESSION-%'
        AND NOT EXISTS (SELECT 1 FROM conversation_messages m
                         WHERE m.conversation_id = c.id AND m.kind = 'decision')
        AND NOT EXISTS (SELECT 1 FROM conversation_links l
                         WHERE l.conversation_id = c.id AND l.linked_type = 'inbox')
        AND EXISTS (SELECT 1 FROM conversation_links l
                     WHERE l.conversation_id = c.id AND l.linked_type = 'session')
      ORDER BY c.id`
  )
  .all()

// Skip any that already carry the annotation, so re-running is idempotent.
const hasAnnotation = db.prepare(
  `SELECT 1 FROM conversation_messages
    WHERE conversation_id = ? AND content LIKE 'TASK-1621 — automated correction%' LIMIT 1`
)
const pending = swept.filter((r) => !hasAnnotation.get(r.id))

console.log(`swept conversations identified: ${swept.length}`)
console.log(`already annotated:              ${swept.length - pending.length}`)
console.log(`pending annotation:             ${pending.length}`)

const bySession = new Map()
for (const r of swept) {
  if (!bySession.has(r.session_id)) bySession.set(r.session_id, [])
  bySession.get(r.session_id).push(r)
}

const lines = [
  '# TASK-1621 — conversations swept closed by `session_end`',
  '',
  `Generated by \`scripts/annotate-1621-swept-conversations.mjs\` against \`${DB_PATH}\`.`,
  '',
  'These threads have `status = decided` and a `decisionSummary` that no `decision` turn',
  'backs — the pre-fix `session_end` wrote the header directly and copied the ending',
  "session's `resumePoint` into it. Grouped by the session that closed them.",
  '',
  '**Decision (2026-08-09): annotate, do not reopen.** Each thread below gets a message turn',
  'saying the close was automated and the summary is not its decision. Status stays `decided`',
  'so long-dead threads do not flood the open-conversation views. Recover individual threads',
  'with the `conversation_reopen` MCP tool.',
  '',
  `Total: **${swept.length}** conversations across **${bySession.size}** sessions.`,
  ''
]

for (const [sessionId, rows] of [...bySession.entries()].sort()) {
  lines.push(`## ${sessionId} — ${rows.length} conversation(s)`, '')
  lines.push('| Conversation | Title | Borrowed summary |')
  lines.push('|---|---|---|')
  for (const r of rows) {
    const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').slice(0, 90)
    lines.push(`| \`${r.id}\` | ${cell(r.title)} | ${cell(r.decision_summary)} |`)
  }
  lines.push('')
}

if (!APPLY) {
  console.log('\nDRY RUN — no writes. Re-run with --apply to annotate + write the report.')
  console.log(`Would write report to: ${REPORT_PATH}`)
  for (const r of pending.slice(0, 5)) console.log(`  would annotate ${r.id} — ${r.title?.slice(0, 60)}`)
  if (pending.length > 5) console.log(`  … and ${pending.length - 5} more`)
  db.close()
  process.exit(0)
}

const insert = db.prepare(
  `INSERT INTO conversation_messages (id, conversation_id, author_name, content, kind, created_at)
   VALUES (?, ?, ?, ?, 'message', ?)`
)

const run = db.transaction(() => {
  const at = new Date().toISOString()
  let n = 0
  for (const r of pending) {
    insert.run(`CONVMSG-1621-${r.id}`, r.id, 'choda-deck', ANNOTATION, at)
    n++
  }
  return n
})

const written = run()
fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true })
fs.writeFileSync(REPORT_PATH, lines.join('\n'), 'utf8')
db.close()

console.log(`\nannotated ${written} conversation(s)`)
console.log(`report written to ${REPORT_PATH}`)
